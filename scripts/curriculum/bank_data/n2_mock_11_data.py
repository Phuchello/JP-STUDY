def _item(qid, type_id, category, stem, options, key, explanation, extra=None):
    if len(options) != 4 or key not in LETTERS:
        raise ValueError(f"Invalid item: {qid}")
    item = {
        "id": qid, "level": "N2", "typeId": type_id, "category": category,
        "stem": stem,
        "options": [{"id": LETTERS[i], "text": text} for i, text in enumerate(options)],
        "correctAnswer": key, "explanation": explanation,
        "explanationVi": explanation,
    }
    item["distractorExplanations"] = {
        LETTERS[i]: f"Phương án «{text}» không trả lời đúng điểm câu hỏi đang yêu cầu. {explanation}"
        for i, text in enumerate(options) if LETTERS[i] != key
    }
    if extra:
        item.update(extra)
    if type_id == "N2-GR-STAR":
        detail = (f" Ở câu này, cụm «{item['starredOptionText']}» đứng ở vị trí thứ ba; "
                  f"câu hoàn chỉnh là «{item['assembledSentence']}». Hãy kiểm tra cả trật tự cụm từ và quan hệ bổ nghĩa trước khi chọn.")
        item["explanation"] += detail
        item["explanationVi"] = item["explanation"]
    return item


