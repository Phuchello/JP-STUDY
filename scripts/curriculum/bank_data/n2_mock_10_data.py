LETTERS = "ABCD"


def _position_pool(pool, labels, seed_prefix):
    """Assign balanced answer labels without changing which text is correct."""
    labels = list(labels)
    chosen = None
    for seed in range(1000):
        ranked = sorted(
            pool,
            key=lambda item: hashlib.sha256(f"{seed_prefix}:{seed}:{item['id']}".encode()).hexdigest(),
        )
        mapping = {item["id"]: labels[i] for i, item in enumerate(ranked)}
        sequence = [mapping[item["id"]] for item in pool]
        longest = run = 1
        for i in range(1, len(sequence)):
            run = run + 1 if sequence[i] == sequence[i - 1] else 1
            longest = max(longest, run)
        if longest <= 3:
            chosen = mapping
            break
    if chosen is None:
        raise ValueError(f"Could not balance answer positions for {seed_prefix}")

    for item in pool:
        old_options = item["options"]
        correct_text = next(o["text"] for o in old_options if o["id"] == item["correctAnswer"])
        old_explanations = item.get("distractorExplanations", {})
        rationale_by_text = {
            o["text"]: old_explanations[o["id"]]
            for o in old_options if o["id"] in old_explanations
        }
        correct_index = LETTERS.index(chosen[item["id"]])
        distractors = [o["text"] for o in old_options if o["text"] != correct_text]
        distractors.sort(key=lambda text: hashlib.sha256(f"{seed_prefix}:{item['id']}:{text}".encode()).hexdigest())
        texts = distractors[:correct_index] + [correct_text] + distractors[correct_index:]
        item["options"] = [{"id": LETTERS[i], "text": text} for i, text in enumerate(texts)]
        item["correctAnswer"] = chosen[item["id"]]
        item["distractorExplanations"] = {
            LETTERS[i]: rationale_by_text[text]
            for i, text in enumerate(texts) if text != correct_text
        }


def _balance_sec1_answer_positions(items):
    pool = [item for item in items if item["typeId"] != "N2-GR-STAR"]
    _position_pool(pool, "ABCD" * 17 + "AB", "N2-MOCK-10-SEC1")


def _q(qid, type_id, category, stem, options, key_index, explanation, why, extra=None):
    assert len(options) == len(why) == 4 and 0 <= key_index < 4
    item = {
        "id": qid,
        "typeId": type_id,
        "category": category,
        "stem": stem,
        "options": [{"id": LETTERS[i], "text": options[i]} for i in range(4)],
        "correctAnswer": LETTERS[key_index],
        "explanation": explanation,
        "explanationVi": explanation,
        "distractorExplanations": {
            LETTERS[i]: why[i] for i in range(4) if i != key_index
        },
    }
    if extra:
        item.update(extra)
    return item


def _passage_fields(text):
    # Keep both names: the engine renders `passage`, while the canonical
    # fingerprint binds `contextPassage`.
    return {"passage": text, "contextPassage": text}


