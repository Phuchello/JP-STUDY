def _item(qid, type_id, category, stem, choices, key_index, explanation_vi,
          *, topic="education-media", difficulty=2, context=None, extra=None):
    if len(choices) != 4 or not 0 <= key_index < 4:
        raise ValueError(f"Invalid item: {qid}")
    indexed = list(enumerate(choices))
    _rng.shuffle(indexed)
    options = [{"id": LETTERS[i], "text": text} for i, (_, text) in enumerate(indexed)]
    key = LETTERS[next(i for i, (source_i, _) in enumerate(indexed) if source_i == key_index)]
    key_text = choices[key_index]
    return {
        "id": qid, "level": "N2", "typeId": type_id, "category": category,
        "stem": stem, "options": options, "correctAnswer": key,
        "explanation": f"正解は「{key_text}」です。",
        "explanationVi": explanation_vi,
        "distractorExplanations": {
            option["id"]: f"Phương án «{option['text']}» không phù hợp với cấu trúc hoặc dữ kiện trong câu. {explanation_vi}"
            for option in options if option["id"] != key
        },
        "topicTag": topic, "difficultyBand": difficulty,
        "distractorStrategy": "意味・文脈・文法形式の対比", "skill": "Language Knowledge",
        **({"contextPassage": context, "passage": context} if context else {}),
        **(extra or {}),
    }


def _star(qid, fragments, explanation_vi, sentence):
    if len(fragments) != 4 or "★" in sentence or sentence != "".join(fragments):
        raise ValueError(f"Invalid STAR construction: {qid}")
    indexed = list(enumerate(fragments))
    _rng.shuffle(indexed)
    options = [{"id": LETTERS[i], "text": text} for i, (_, text) in enumerate(indexed)]
    ids = {source_i: LETTERS[i] for i, (source_i, _) in enumerate(indexed)}
    return {
        "id": qid, "level": "N2", "typeId": "N2-GR-STAR", "category": "文の組み立て",
        "stem": "次の文を完成させるとき、★に入る部分はどれか。\n（　　）（　　）★（　　）",
        "options": options, "correctAnswer": ids[2],
        "explanation": "語句の係り受けを確認して文を組み立てます。",
        "explanationVi": explanation_vi,
        "distractorExplanations": {
            option["id"]: f"Cụm «{option['text']}» không đứng ở vị trí ★ trong trật tự tự nhiên. {explanation_vi}"
            for option in options if option["id"] != ids[2]
        },
        "topicTag": "education-media", "difficultyBand": 2,
        "assembledSentence": sentence, "starredOptionText": fragments[2],
        "starPosition": 3, "fragmentOrder": "→".join(ids[i] for i in range(4)),
        "starValidationSchema": "DISPLAYED_FRAGMENT_ORDER_V1",
        "distractorStrategy": "語順・係り受け", "skill": "Language Knowledge",
    }


