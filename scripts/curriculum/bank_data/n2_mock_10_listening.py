def _q(qid, type_id, category, script, stem, options, key, explanation, why):
    width = 3 if type_id == "N2-LIS-RESP" else 4
    if len(options) != width or len(why) != width:
        raise ValueError(f"{qid}: expected {width} aligned options and rationales")
    return {
        "id": qid,
        "typeId": type_id,
        "category": category,
        "script": script,
        "stem": stem,
        "options": [{"id": LETTERS[i], "text": text} for i, text in enumerate(options)],
        "correctAnswer": LETTERS[key],
        "explanation": explanation,
        "explanationVi": explanation,
        "distractorExplanations": {
            LETTERS[i]: why[i] for i in range(width) if i != key
        },
    }


